-- Resource-scope cleanup behaviors.
require("test.bootstrap").install_package_paths()
local luassert = assert
local logger = require("src.foundation.log")
local scope = require("src.foundation.scope")
describe("TestScope", function()
  it("test_runs_cleanup_in_lifo_order_and_ignores_return_values", function()
    local order, resource_scope = {}, scope.new()
    resource_scope:defer(function() order[#order + 1] = "first"; return "not an error" end)
    resource_scope:defer(function() order[#order + 1] = "second" end)
    resource_scope:destroy()
    luassert.is.same({ "second", "first" }, order)
  end)
  it("test_invokes_cleanup_without_arguments", function()
    local argument_count, resource_scope = nil, scope.new()
    resource_scope:defer(function(...) argument_count = select("#", ...) end)
    resource_scope:destroy()
    luassert.is.equal(0, argument_count)
  end)
  it("test_destroy_is_idempotent_and_reentrant", function()
    local calls, resource_scope = 0, scope.new()
    resource_scope:defer(function() calls = calls + 1; resource_scope:destroy() end)
    resource_scope:destroy(); resource_scope:destroy()
    -- lint-allow: call-count scope 契约:defer 回调恰好执行一次(幂等/重入/已销毁立即执行)
    luassert.is.equal(1, calls)
  end)
  it("test_destroy_continues_after_cleanup_errors_and_raises_first_error", function()
    local calls, warnings, original_warn = {}, {}, logger.warn
    logger.warn = function(...) warnings[#warnings + 1] = table.concat({ ... }, " ") end
    local resource_scope = scope.new()
    resource_scope:defer(function() calls[#calls + 1] = "first"; error("first cleanup error") end)
    resource_scope:defer(function() calls[#calls + 1] = "second"; error("second cleanup error") end)
    local ok, err = pcall(function() resource_scope:destroy() end)
    logger.warn = original_warn
    luassert.is_false(ok)
    luassert.matches("second cleanup error", tostring(err), 1, true)
    luassert.is.same({ "second", "first" }, calls)
    luassert.is.equal(1, #warnings)
    luassert.matches("first cleanup error", warnings[1], 1, true)
  end)
  it("test_defer_on_destroyed_scope_runs_immediately", function()
    local calls, resource_scope = 0, scope.new()
    resource_scope:destroy()
    resource_scope:defer(function() calls = calls + 1 end)
    -- lint-allow: call-count scope 契约:defer 回调恰好执行一次(幂等/重入/已销毁立即执行)
    luassert.is.equal(1, calls)
  end)
  it("test_defer_during_destruction_is_rejected", function()
    local resource_scope = scope.new()
    resource_scope:defer(function()
      luassert.has_error.match(function() resource_scope:defer(function() end) end, "destroying scope", 1, true)
    end)
    resource_scope:destroy()
  end)
  it("test_scope_has_no_active_cleanup_after_destroy", function()
    local calls, resource_scope = 0, scope.new()
    resource_scope:defer(function() calls = calls + 1 end)
    resource_scope:destroy()
    resource_scope:defer(function() calls = calls + 1 end)
    resource_scope:destroy()
    -- lint-allow: call-count scope 契约:defer 回调恰好执行一次(幂等/重入/已销毁立即执行)
    luassert.is.equal(2, calls)
  end)
  it("test_cleanup_error_with_nil_value_still_fails_destroy", function()
    local resource_scope = scope.new()
    resource_scope:defer(function() error(nil) end)
    local ok = pcall(function() resource_scope:destroy() end)
    luassert.is_false(ok)
  end)
end)
