if arg then rawset(arg, 0, "tools/foundation/test/test_platform_boundary.lua") end
require("test.bootstrap").install_package_paths()
local check = require("luassert")
local boundary = require("foundation.platform_boundary")
local fixture = { fixture = { id = "fixture", title = "test capability", reason = "fixture reason" } }
local function evaluate(args, platform)
  return boundary.evaluate("fixture", args, platform or "posix", fixture)
end

describe("platform boundary", function()
  it("distinguishes unavailable and explicit skip for declared capabilities", function()
    local unavailable = evaluate({ "input" })
    check.same("unavailable", unavailable.status)
    check.same(3, unavailable.exit_code)
    check.same("stderr", unavailable.stream)
    check.matches("status=unavailable", unavailable.message, 1, true)
    local skipped = evaluate({ "--skip-if-unavailable", "input" })
    check.same("skipped", skipped.status)
    check.same(0, skipped.exit_code)
    check.same("stdout", skipped.stream)
    check.same({ "input" }, skipped.args)
    check.matches("status=skipped", skipped.message, 1, true)
  end)
  it("forwards supported requests after consuming skip flag", function()
    local verdict = evaluate({ "--skip-if-unavailable", "--json", "input" }, "linux")
    check.is_nil(verdict.status)
    check.same({ "--json", "input" }, verdict.args)
  end)
  it("rejects an undeclared capability", function()
    check.has_error(function() boundary.evaluate("unknown", {}, "linux") end)
  end)
  it("reports the WSL Ubuntu guarantee face and distinct unavailable exit code", function()
    check.same("linux", boundary.host_platform())
    check.is_true(boundary.supported_platform("linux"))
    check.is_false(boundary.supported_platform("windows"))
    check.same(3, boundary.UNAVAILABLE_EXIT_CODE)
  end)
end)
